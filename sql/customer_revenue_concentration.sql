
USE RetailAnalyticsDB;
GO

-- Calculate total revenue for each customer with a known CustomerID.
WITH CustomerRevenue AS (
    SELECT
        CAST(CustomerID AS INT) AS CustomerID,
        SUM(Revenue) AS TotalCustomerRevenue
    FROM dbo.retail_sales_cleaned
    WHERE CustomerID IS NOT NULL
    GROUP BY CAST(CustomerID AS INT)
),

-- Rank customers from highest to lowest revenue.
RankedCustomers AS (
    SELECT
        CustomerID,
        TotalCustomerRevenue,

        -- Assign rank 1 to the highest-revenue customer.
        ROW_NUMBER() OVER (
            ORDER BY TotalCustomerRevenue DESC, CustomerID
        ) AS CustomerRank,

        -- Calculate total revenue from customers with known IDs.
        SUM(TotalCustomerRevenue) OVER () AS KnownCustomerRevenue,

        -- Count all customers with known IDs.
        COUNT(*) OVER () AS TotalKnownCustomers
    FROM CustomerRevenue
)

-- Measure the revenue contribution of the top 10% of customers.
SELECT
    MAX(TotalKnownCustomers) AS TotalKnownCustomers,

    -- Calculate the number of customers in the top 10%.
    CEILING(MAX(TotalKnownCustomers) * 0.10)
        AS Top10PercentCustomerCount,

    -- Total revenue from customers with known IDs.
    CAST(MAX(KnownCustomerRevenue) AS DECIMAL(18, 2))
        AS TotalKnownCustomerRevenue,

    -- Revenue generated by the top 10% of customers.
    CAST(
        SUM(
            CASE
                WHEN CustomerRank <=
                     CEILING(TotalKnownCustomers * 0.10)
                THEN TotalCustomerRevenue
                ELSE 0
            END
        )
        AS DECIMAL(18, 2)
    ) AS Top10PercentRevenue,

    -- Percentage of known-customer revenue generated by the top 10%.
    CAST(
        100.0 *
        SUM(
            CASE
                WHEN CustomerRank <=
                     CEILING(TotalKnownCustomers * 0.10)
                THEN TotalCustomerRevenue
                ELSE 0
            END
        )
        / NULLIF(MAX(KnownCustomerRevenue), 0)
        AS DECIMAL(5, 2)
    ) AS Top10PercentRevenueShare

FROM RankedCustomers;
GO
